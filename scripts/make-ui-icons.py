#!/usr/bin/env python3
"""Generate native vector paths from the normalized, stroke-only SVG sources."""
from pathlib import Path
import re
import xml.etree.ElementTree as ET
root = Path(__file__).resolve().parent.parent
icons = {'overview': 'gongzuotai', 'groups': 'qunliao', 'contacts': 'danliao', 'activity': 'xitongrizhi', 'settings': 'shezhi'}
lines = ['// Generated by scripts/make-ui-icons.py from Assets/Icons/*.svg.', 'import SwiftUI', '', 'struct DashboardIcon: Shape {', '    enum Kind { case overview, groups, contacts, activity, settings }', '    let kind: Kind', '    func path(in rect: CGRect) -> Path {', '        var path = Path()', '        switch kind {']
def point(x,y): return f'CGPoint(x: {x:g}, y: {y:g})'
for kind, name in icons.items():
    svg = ET.parse(root/'Assets/Icons'/f'{name}.svg').getroot()
    assert svg.get('viewBox') == '0 0 24 24'
    lines.append(f'        case .{kind}:')
    for el in svg:
        tag = el.tag.split('}')[-1]; a = el.attrib
        if tag == 'circle':
            x,y,r = (float(a[k]) for k in ['cx','cy','r'])
            lines.append(f'            path.addEllipse(in: CGRect(x: {x-r:g}, y: {y-r:g}, width: {r*2:g}, height: {r*2:g}))')
        elif tag == 'rect':
            x,y,w,h,r = (float(a[k]) for k in ['x','y','width','height','rx'])
            lines.append(f'            path.addRoundedRect(in: CGRect(x: {x:g}, y: {y:g}, width: {w:g}, height: {h:g}), cornerSize: CGSize(width: {r:g}, height: {r:g}))')
        elif tag == 'path':
            tokens = re.findall(r'[A-Za-z]|[-+]?(?:\d*\.\d+|\d+)(?:[eE][-+]?\d+)?', a['d'])
            i=0; x=y=0; start=(0,0)
            while i < len(tokens):
                cmd=tokens[i];i+=1
                count={'M':2,'L':2,'H':1,'V':1,'C':6,'Q':4,'Z':0}[cmd]
                n=list(map(float,tokens[i:i+count]));i+=count
                if cmd=='M': x,y=n;start=(x,y);s=f'path.move(to: {point(x,y)})'
                elif cmd=='L': x,y=n;s=f'path.addLine(to: {point(x,y)})'
                elif cmd=='H': x=n[0];s=f'path.addLine(to: {point(x,y)})'
                elif cmd=='V': y=n[0];s=f'path.addLine(to: {point(x,y)})'
                elif cmd=='C': x,y=n[4:];s=f'path.addCurve(to: {point(x,y)}, control1: {point(*n[:2])}, control2: {point(*n[2:4])})'
                elif cmd=='Q': x,y=n[2:];s=f'path.addQuadCurve(to: {point(x,y)}, control: {point(*n[:2])})'
                else: x,y=start;s='path.closeSubpath()'
                lines.append('            '+s)
        else: raise ValueError(tag)
lines += ['        }', '        let scale = min(rect.width, rect.height) / 24', '        return path.applying(CGAffineTransform(a: scale, b: 0, c: 0, d: scale,', '                                             tx: rect.midX - 12 * scale, ty: rect.midY - 12 * scale))', '    }', '}', '', 'struct DashboardGlyph: View {', '    let kind: DashboardIcon.Kind', '    var size: CGFloat = 22', '    var body: some View {', '        DashboardIcon(kind: kind)', '            .stroke(style: StrokeStyle(lineWidth: size * 1.65 / 24, lineCap: .round, lineJoin: .round))', '            .frame(width: size, height: size)', '            .accessibilityHidden(true)', '    }', '}', '']
(root/'Sources/DWSAssistant/DashboardIcon.swift').write_text('\n'.join(lines))
